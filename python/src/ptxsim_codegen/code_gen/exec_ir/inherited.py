from ptxsim_codegen.model.names import cpp_identifier as identifier


def _layout_name(value: str) -> str:
    """Name a layout-local operand record independently of frontend member aliases."""
    return ''.join(part[:1].upper() + part[1:] for part in re.split(r'[^A-Za-z0-9]+', value) if part) + 'Operands'


def _warning() -> str:
    """Return a deterministic artifact banner."""
    return '// Generated by ptxsim_codegen.code_gen.exec_ir. Do not edit.\n'


def domain_header(model: Snapshot) -> str:
    """Declare every owned semantic enum and its out-of-line diagnostic API."""
    lines = [_warning(), '#pragma once\n#include <cstdint>\n#include <string_view>\n', 'namespace ptxsim::exec_ir {\n']
    for domain in model.domains:
        if domain.cpp_type == 'bool':
            continue
        lines += [f'/** @brief Owned {domain.kind.value} semantic domain. */\n',
                  f'enum class {domain.cpp_type} : std::uint16_t {{\n']
        lines += [f'  {value.cpp.split("::")[-1]} = {value.ordinal},\n' for value in domain.values]
        lines += ['};\n', f'/** @brief Return the original semantic spelling of {domain.cpp_type}. */\n',
                  f'[[nodiscard]] auto to_string({domain.cpp_type}) noexcept -> std::string_view;\n',
                  f'/** @brief Test membership in the complete {domain.cpp_type} domain. */\n',
                  f'[[nodiscard]] auto is_valid({domain.cpp_type}) noexcept -> bool;\n']
    domain = model.atomic_qualifier_domain
    lines += ['/** @brief Selected atomic address qualifier, independent of canonical space. */\n',
              f'enum class {domain.cpp_type} : std::uint8_t {{\n']
    lines += [f'  {value.cpp.split("::")[-1]},\n' for value in domain.values]
    lines += ['};\n', '/** @brief Format the complete selected atomic qualifier. */\n',
              f'[[nodiscard]] auto to_string({domain.cpp_type}) noexcept -> std::string_view;\n',
              '/** @brief Check the selected atomic qualifier domain. */\n',
              f'[[nodiscard]] auto is_valid({domain.cpp_type}) noexcept -> bool;\n',
              '}  // namespace ptxsim::exec_ir\n']
    return ''.join(lines)


def domain_source(model: Snapshot) -> str:
    """Define complete diagnostic/membership mappings without enum reflection limits."""
    lines = [_warning(), '#include <ptxsim/exec_ir/value_domains.gen.hpp>\nnamespace ptxsim::exec_ir {\n']
    domains = [(domain.cpp_type, tuple((value.cpp, value.spelling) for value in domain.values))
               for domain in model.domains if domain.cpp_type != 'bool']
    domains.append((model.atomic_qualifier_domain.cpp_type,
                    tuple((value.cpp, value.semantic.value) for value in model.atomic_qualifier_domain.values)))
    for cpp_type, values in domains:
        lines += [f'auto to_string({cpp_type} value) noexcept -> std::string_view {{\n  switch (value) {{\n']
        lines += [f'    case {cpp}: return {json.dumps(str(spelling))};\n' for cpp, spelling in values]
        lines += ['  }\n  return "<invalid>";\n}\n',
                  f'auto is_valid({cpp_type} value) noexcept -> bool {{\n  switch (value) {{\n']
        lines += [f'    case {cpp}:\n' for cpp, _ in values]
        lines += ['      return true;\n  }\n  return false;\n}\n']
    lines += ['}  // namespace ptxsim::exec_ir\n']
    return ''.join(lines)


def base_header(model: Snapshot) -> str:
    """Declare closed construction, dense identity and exact generated-form queries."""
    forms = model.forms
    lines = [_warning(), '#pragma once\n#include <concepts>\n#include <cstddef>\n#include <cstdint>\n#include <memory>\n#include <optional>\n#include <string>\n#include <type_traits>\n#include <utility>\n#include <ptxsim/exec_ir/owned_operands.hpp>\n#include <ptxsim/exec_ir/instruction_contracts.hpp>\n',
             'namespace ptxsim::exec_ir {\n',
             '/** @brief Dense opcode identity; named values are in the optional catalogue. */\n',
             'enum class Opcode : std::uint16_t;\n',
             '/** @brief Dense exact-form identity; named values are in the optional catalogue. */\n',
             'enum class Kind : std::uint16_t;\n',
             f'/** @brief Number of exact forms in this immutable generation snapshot. */\ninline constexpr std::size_t instruction_kind_count = {len(forms)};\n',
             f'/** @brief Number of opcode families in this immutable generation snapshot. */\ninline constexpr std::size_t opcode_count = {len(model.instructions)};\n']
    lines += [f'/** @brief Forward declaration of exact semantic form {form.identity.variant}. */\nclass {form.cpp_name};\n' for form in forms]
    lines += ['namespace detail {\n/** @brief Closed opt-in defined only for generated final classes. */\ntemplate <typename T> inline constexpr bool generated_form = false;\n}\n',
              '/** @brief Exact generated-form constraint; arbitrary user types are excluded. */\n',
              'template <typename T> concept GeneratedForm = detail::generated_form<std::remove_cv_t<T>>;\n',
              '/** @brief Polymorphic owned instruction with immutable identity and no executor. */\n',
              'class Instruction {\n public:\n',
              '  /** @brief Destroy the actual final owned operand/control object. */\n  virtual ~Instruction() = default;\n',
              '  /** @brief Return the immutable dense exact-form identity. */\n  [[nodiscard]] auto instruction_kind() const noexcept -> Kind { return kind_; }\n',
              '  /** @brief Return the immutable opcode identity. */\n  [[nodiscard]] auto instruction_opcode() const noexcept -> Opcode { return opcode_; }\n',
              '  /** @brief Execution predicate; mutable only while this is caller-owned input. */\n  std::optional<Predicate> execution_predicate;\n',
              '  /** @brief Query an exact generated final type without RTTI. */\n',
              '  template <GeneratedForm T> [[nodiscard]] auto get_if() const noexcept -> const T* {\n',
              '    return kind_ == T::kind ? static_cast<const T*>(this) : nullptr;\n  }\n',
              '  /** @brief Query a mutable caller-owned builder object without changing identity. */\n',
              '  template <GeneratedForm T> [[nodiscard]] auto get_if() noexcept -> T* {\n',
              '    return kind_ == T::kind ? static_cast<T*>(this) : nullptr;\n  }\n',
              ' private:\n',
              '  /** @brief Construct identity only from a generated exact final friend. */\n',
              '  Instruction(Kind kind, Opcode opcode, std::optional<Predicate> predicate)\n',
              '      : execution_predicate(std::move(predicate)), kind_(kind), opcode_(opcode) {}\n',
              '  /** @brief Copy common state only as part of a generated exact final copy. */\n  Instruction(const Instruction&) = default;\n',
              '  /** @brief Move common state only as part of a generated exact final move. */\n  Instruction(Instruction&&) noexcept = default;\n',
              '  /** @brief Fixed exact identity; assignment cannot retag an existing object. */\n  const Kind kind_;\n',
              '  /** @brief Fixed opcode identity paired with the exact final type. */\n  const Opcode opcode_;\n']
    lines += [f'  friend class {form.cpp_name};\n' for form in forms]
    lines += ['};\n',
              '/** @brief Check owned shape invariants through one generated exact-form thunk. */\n[[nodiscard]] auto structurally_valid(const Instruction&) noexcept -> bool;\n',
              '/** @brief Print all selected owned fields without frontend lifetime dependencies. */\n[[nodiscard]] auto to_string(const Instruction&) -> std::string;\n',
              '/** @brief Deep-copy an exact form into fresh actual const storage. */\n[[nodiscard]] auto freeze_instruction(const Instruction&) -> std::unique_ptr<const Instruction>;\n',
              '/** @brief Query complete static facts; invalid externally cast Kind returns null. */\n[[nodiscard]] auto form_contract(Kind) noexcept -> const FormContract*;\n',
              '}  // namespace ptxsim::exec_ir\n']
    return ''.join(lines)


def catalogue(model: Snapshot) -> str:
    """Expose optional named enumerators without including final class definitions."""
    lines = [_warning(), '#pragma once\n#include <ptxsim/exec_ir/instruction_base.gen.hpp>\nnamespace ptxsim::exec_ir {\n',
             '/** @brief Complete dense named opcode catalogue. */\nenum class Opcode : std::uint16_t {\n']
    lines += [f'  {op.cpp_name} = {op.identity},\n' for op in model.instructions]
    lines += ['};\n/** @brief Complete dense named exact-form catalogue. */\nenum class Kind : std::uint16_t {\n']
    lines += [f'  {form.cpp_name} = {form.kind},\n' for form in model.forms]
    lines += ['};\n}  // namespace ptxsim::exec_ir\n']
    return ''.join(lines)


def _declaration(form: Form, model: Snapshot) -> str:
    """Declare one final direct subclass and all of its typed selected layouts."""
    dynamic = tuple(field for field in form.modifiers if field.storage is FieldStorage.INSTANCE)
    lines = [f'/** @brief Exact owned {form.identity.opcode}/{form.identity.variant} semantic form. */\nclass {form.cpp_name} final : public Instruction {{\n public:\n',
             f'  /** @brief Fixed dense exact identity. */\n  inline static constexpr Kind kind = static_cast<Kind>({form.kind});\n',
             f'  /** @brief Fixed dense opcode identity. */\n  inline static constexpr Opcode opcode = static_cast<Opcode>({form.opcode});\n']
    lines += [f'  /** @brief Exact implicit condition-code contract. */\n  inline static constexpr ConditionCodeEffect condition_code_effect = ConditionCodeEffect::{form.contracts.condition_code.name};\n',
              f'  /** @brief Exact asynchronous completion contract. */\n  inline static constexpr AsyncCompletionKind completion_kind = AsyncCompletionKind::{form.contracts.completion.name};\n',
              f'  /** @brief Exact selected WGMMA protocol action. */\n  inline static constexpr WgmmaProtocolAction wgmma_protocol_action = WgmmaProtocolAction::{form.contracts.wgmma_action.name};\n']
    if form.contracts.floating_point_default is not None:
        lines += [f'  /** @brief Selected interpretation of omitted floating controls. */\n  inline static constexpr FloatingPointDefault floating_point_default = FloatingPointDefault::{form.contracts.floating_point_default.name};\n']
    lines += ['  /** @brief Query the complete owned static contract without frontend data. */\n  [[nodiscard]] static auto static_contract() noexcept -> const FormContract&;\n']
    for field in form.modifiers:
        if field.storage is FieldStorage.CONSTANT:
            lines += [f'  /** @brief Fixed semantic control {field.identity.name}. */\n  inline static constexpr {field.cpp_type} {identifier(field.cpp_name)} = {field.constant.cpp};\n']
    for layout in form.layouts:
        lines += [f'  /** @brief Complete selected {layout.identity.name} operand layout. */\n  struct {_layout_name(layout.identity.name)} {{\n']
        for field in layout.fields:
            lines += [f'    /** @brief Owned {field.identity.name} operand value; no frontend references. */\n    {field.cpp_type} {identifier(field.cpp_name)}{{}};\n']
        lines += [f'    /** @brief Compare every owned operand in this selected layout. */\n    bool operator==(const {_layout_name(layout.identity.name)}&) const = default;\n  }};\n']
    layout_types = [_layout_name(layout.identity.name) for layout in form.layouts]
    operands_type = layout_types[0] if len(layout_types) == 1 else 'std::variant<' + ', '.join(layout_types) + '>'
    lines += [f'  /** @brief Closed set of actual semantic layouts for this exact form. */\n  using Operands = {operands_type};\n',
              '  /** @brief Mutable construction inputs, copied into direct typed controls. */\n  struct Controls {\n']
    for field in dynamic:
        default = field.default or field.domain[0]
        lines += [f'    /** @brief Selected {field.identity.name} semantic value. */\n    {field.cpp_type} {identifier(field.cpp_name)}{{{default.cpp}}};\n']
    if form.atomic_qualifier is not None:
        lines += [f'    /** @brief Selected atomic suffix, independent of canonical memory space. */\n    {model.atomic_qualifier_domain.cpp_type} address_qualifier{{{form.atomic_qualifier.allowed[0].cpp}}};\n']
    lines += ['  };\n']
    for field in dynamic:
        lines += [f'  /** @brief Selected owned {field.identity.name} control. */\n  {field.cpp_type} {identifier(field.cpp_name)};\n']
    if form.atomic_qualifier is not None:
        lines += [f'  /** @brief Actual selected atomic address qualifier. */\n  {model.atomic_qualifier_domain.cpp_type} address_qualifier;\n']
    lines += ['  /** @brief Exactly one complete owned semantic operand layout. */\n  Operands operands;\n',
              f'  /** @brief Construct selected operands with normalized control defaults. */\n  explicit {form.cpp_name}(Operands, std::optional<Predicate> = std::nullopt);\n',
              f'  /** @brief Construct every selected control and operand, fixing both identities. */\n  {form.cpp_name}(Operands, Controls, std::optional<Predicate> = std::nullopt);\n',
              f'  /** @brief Deep-value-copy this exact form without changing its fixed identity. */\n  {form.cpp_name}(const {form.cpp_name}&) = default;\n',
              f'  /** @brief Move this exact caller-owned input without permitting retagging. */\n  {form.cpp_name}({form.cpp_name}&&) noexcept = default;\n',
              '};\n',
              f'namespace detail {{ template <> inline constexpr bool generated_form<{form.cpp_name}> = true; }}\n']
    return ''.join(lines)


def opcode_header(op: Instruction, model: Snapshot, shard: tuple[Form, ...] | None = None) -> str:
    """Emit a bounded narrow public model header."""
    forms = op.forms if shard is None else shard
    lines = [_warning(), '#pragma once\n#include <variant>\n#include <ptxsim/exec_ir/instruction_base.gen.hpp>\n#include <ptxsim/exec_ir/form_contracts.gen.hpp>\nnamespace ptxsim::exec_ir {\n']
    lines += [_declaration(form, model) for form in forms]
    lines += ['}  // namespace ptxsim::exec_ir\n']
    return ''.join(lines)


def constructor_source(op: Instruction, shard_index: int, forms: tuple[Form, ...], model: Snapshot,
                       contracts: ContractSchema) -> str:
    """Define constructor/freeze thunks out of public class headers."""
    path = f'model/{op.category}/{op.opcode}_forms_{shard_index:03d}.gen.hpp'
    lines = [_warning(), f'#include <ptxsim/exec_ir/{path}>\n#include <ptxsim/exec_ir/exec_ir_types.hpp>\n#include <array>\n#include <utility>\nnamespace ptxsim::exec_ir {{\n']
    for form in forms:
        name = form.cpp_name
        dynamic = [field for field in form.modifiers if field.storage is FieldStorage.INSTANCE]
        lines += [f'{name}::{name}(Operands values, std::optional<Predicate> predicate)\n',
                  f'    : {name}(std::move(values), Controls{{}}, std::move(predicate)) {{}}\n',
                  f'{name}::{name}(Operands values, Controls selected, std::optional<Predicate> predicate)\n',
                  '    : Instruction(kind, opcode, std::move(predicate))']
        lines += [f',\n      {identifier(field.cpp_name)}(selected.{identifier(field.cpp_name)})' for field in dynamic]
        if form.atomic_qualifier is not None:
            lines += [',\n      address_qualifier(selected.address_qualifier)']
        lines += [',\n      operands(std::move(values)) {}\n',
                  f'/** @brief Freeze an actual const {name} with independent nested value storage. */\n',
                  f'auto freeze_{name}(const Instruction& value) -> std::unique_ptr<const Instruction> {{\n',
                  f'  return std::make_unique<const {name}>(static_cast<const {name}&>(value));\n}}\n']
    lines += [_form_thunks(form) for form in forms]
    lines += [contract_source(contracts, forms, f'{op.category}_{op.opcode}_{shard_index:03d}')]
    lines += ['}  // namespace ptxsim::exec_ir\n']
    return ''.join(lines)


@dataclass(frozen=True)
class ArtifactPlan:
    """Complete deterministic output membership needed by CMake and generation."""

    headers: tuple[str, ...]
    sources: tuple[str, ...]


def artifact_plan(model: Snapshot) -> ArtifactPlan:
    """Partition final classes and methods into at most 64-form compile units."""
    headers = ['value_domains.gen.hpp', 'instruction_base.gen.hpp', 'instruction_catalogue.gen.hpp', 'form_contracts.gen.hpp', 'exec_ir.gen.hpp']
    sources = ['value_domains.gen.cpp', 'ir_dispatch.gen.cpp']
    for op in model.instructions:
        headers.append(f'model/{op.category}/{op.opcode}.gen.hpp')
        for index in range((len(op.forms) + 63) // 64):
            headers.append(f'model/{op.category}/{op.opcode}_forms_{index:03d}.gen.hpp')
            sources.append(f'{op.category}_{op.opcode}_methods_{index:03d}.gen.cpp')
    return ArtifactPlan(tuple(headers), tuple(sources))


def generate(model: Snapshot, root: Path) -> ArtifactPlan:
    """Publish the full independent owned class hierarchy and constructor sources."""
    plan = artifact_plan(model)
    contracts = ContractSchema(model)
    public = root / 'public/ptxsim/exec_ir'
    atomic_write(public / 'form_contracts.gen.hpp', contracts.header())
    atomic_write(public / 'value_domains.gen.hpp', domain_header(model))
    atomic_write(root / 'value_domains.gen.cpp', domain_source(model))
    atomic_write(root / 'ir_dispatch.gen.cpp', dispatch_source(model))
    atomic_write(public / 'instruction_base.gen.hpp', base_header(model))
    atomic_write(public / 'instruction_catalogue.gen.hpp', catalogue(model))
    aggregate = [_warning(), '#pragma once\n#include <ptxsim/exec_ir/instruction_catalogue.gen.hpp>\n']
    for op in model.instructions:
        includes = [_warning(), '#pragma once\n']
        for index, begin in enumerate(range(0, len(op.forms), 64)):
            shard = op.forms[begin:begin + 64]
            filename = f'{op.opcode}_forms_{index:03d}.gen.hpp'
            atomic_write(public / f'model/{op.category}/{filename}', opcode_header(op, model, shard))
            atomic_write(root / f'{op.category}_{op.opcode}_methods_{index:03d}.gen.cpp', constructor_source(op, index, shard, model, contracts))
            includes += [f'#include <ptxsim/exec_ir/model/{op.category}/{filename}>\n']
        atomic_write(public / f'model/{op.category}/{op.opcode}.gen.hpp', ''.join(includes))
        aggregate += [f'#include <ptxsim/exec_ir/model/{op.category}/{op.opcode}.gen.hpp>\n']
    atomic_write(public / 'exec_ir.gen.hpp', ''.join(aggregate))
    atomic_write(root / 'artifact_plan.json', json.dumps({'headers': plan.headers, 'sources': plan.sources}, indent=2) + '\n')
    return plan


def _form_thunks(form: Form) -> str:
    """Generate exact owned shape/printing operations from projection fields."""
    from ptxsim_codegen.model.snapshot import SourceContext, ValueKind
    name = form.cpp_name
    lines = [f'/** @brief Validate {name} owned structure without executing operands. */\n',
             f'auto validate_{name}(const Instruction& base) noexcept -> bool {{\n',
             f'  const auto& value = static_cast<const {name}&>(base);\n',
             '  if (value.execution_predicate && !valid_operand(*value.execution_predicate)) return false;\n']
    for field in form.modifiers:
        if field.storage is FieldStorage.INSTANCE:
            condition = ' || '.join(f'value.{identifier(field.cpp_name)} == {atom.cpp}' for atom in field.domain)
            lines += [f'  if (!({condition})) return false;\n']
    if form.atomic_qualifier is not None:
        condition = ' || '.join(f'value.address_qualifier == {atom.cpp}' for atom in form.atomic_qualifier.allowed)
        lines += [f'  if (!({condition})) return false;\n']
        for field in form.modifiers:
            if field.value_kind is ValueKind.MEMORY_STATE_SPACE:
                lines += [f'  if (!atomic_space_matches(value.{identifier(field.cpp_name)}, value.address_qualifier)) return false;\n']
    if len(form.layouts) > 1:
        lines += ['  if (value.operands.valueless_by_exception()) return false;\n  switch (value.operands.index()) {\n']
    for layout in form.layouts:
        indent = '    ' if len(form.layouts) > 1 else '  '
        if len(form.layouts) > 1:
            lines += [f'    case {layout.index}: {{\n      const auto& operands = std::get<{layout.index}>(value.operands);\n']
            indent = '      '
        else:
            lines += ['  const auto& operands = value.operands;\n']
        for field in layout.fields:
            lines += [f'{indent}if (!valid_operand(operands.{identifier(field.cpp_name)})) return false;\n']
            binding = field.binding
            predicate_outputs = {ValueKind.PREDICATE, ValueKind.PREDICATE_OR_SINK,
                                 ValueKind.PREDICATE_PAIR, ValueKind.PREDICATE_PAIR_OR_SINK,
                                 ValueKind.SHFL_DESTINATION, ValueKind.TEXTURE_RESULT}
            if binding is not None and binding.role.name == 'DESTINATION' and field.value_kind in predicate_outputs:
                lines += [f'{indent}if (!valid_predicate_destination(operands.{identifier(field.cpp_name)})) return false;\n']
            if binding is not None and (binding.minimum_elements is not None or binding.maximum_elements is not None or binding.allowed_vector_arities):
                supported = {ValueKind.REGISTER_VECTOR, ValueKind.VALUE_VECTOR, ValueKind.MOV_VECTOR_SOURCE,
                             ValueKind.TENSOR_COORDINATE, ValueKind.TENSOR_IM2COL_INFO, ValueKind.CALL_ARGUMENTS,
                             ValueKind.TENSOR_OPERAND, ValueKind.TEXTURE_RESULT, ValueKind.MATRIX_SCALE_SELECTOR}
                if field.value_kind not in supported:
                    raise ValueError(f'unmapped structural cardinality: {field.identity}/{field.value_kind}')
                count = 'count_' + identifier(field.cpp_name)
                lines += [f'{indent}const auto {count} = operand_cardinality(operands.{identifier(field.cpp_name)});\n']
                if binding.minimum_elements is not None:
                    lines += [f'{indent}if ({count} && *{count} < {binding.minimum_elements}) return false;\n']
                if binding.maximum_elements is not None:
                    lines += [f'{indent}if ({count} && *{count} > {binding.maximum_elements}) return false;\n']
                if binding.allowed_vector_arities:
                    allowed = ' || '.join(f'*{count} == {size}' for size in binding.allowed_vector_arities)
                    lines += [f'{indent}if ({count} && !({allowed})) return false;\n']
                if binding.vector_arity_modifier_field_id is not None:
                    control = next(control for control in form.modifiers if control.identity.name == binding.vector_arity_modifier_field_id)
                    if control.value_kind is not ValueKind.VECTOR_ARITY:
                        raise ValueError(f'non-vector arity control: {control.identity}')
                    lines += [f'{indent}if ({count} && *{count} != vector_arity_size(value.{identifier(control.cpp_name)})) return false;\n']
        for control in form.modifiers:
            if any(group.context is SourceContext.PARAMETER_QUALIFIER for group in control.source_groups):
                for field in layout.fields:
                    if field.value_kind is ValueKind.ADDRESS:
                        lines += [f'{indent}if (!parameter_space_matches(value.{identifier(control.cpp_name)}, operands.{identifier(field.cpp_name)}.parameter_qualifier)) return false;\n']
        if len(form.layouts) > 1:
            lines += ['      return true;\n    }\n']
    lines += ['    default: return false;\n  }\n}\n' if len(form.layouts) > 1 else '  return true;\n}\n']
    lines += [f'/** @brief Print every selected native field of {name}. */\n',
              f'auto print_{name}(const Instruction& base) -> std::string {{\n',
              f'  const auto& value = static_cast<const {name}&>(base);\n',
              f'  std::string output{{{json.dumps(form.identity.opcode + "/" + form.identity.variant)}}};\n',
              '  if (value.execution_predicate) output += " @" + to_string(*value.execution_predicate);\n']
    for field in form.modifiers:
        expression = f'value.{identifier(field.cpp_name)}'
        text = f'({expression} ? "true" : "false")' if field.cpp_type == 'bool' else f'std::string{{to_string({expression})}}'
        lines += [f'  output += {json.dumps(" " + field.identity.name + "=")} + std::string{{{text}}};\n']
    if form.atomic_qualifier is not None:
        lines += ['  output += " address_qualifier=" + std::string{to_string(value.address_qualifier)};\n']
    if len(form.layouts) > 1:
        lines += ['  if (value.operands.valueless_by_exception()) return output + " <valueless-layout>";\n  switch (value.operands.index()) {\n']
    for layout in form.layouts:
        indent = '  '
        if len(form.layouts) > 1:
            lines += [f'    case {layout.index}: {{\n      const auto& operands = std::get<{layout.index}>(value.operands);\n']
            indent = '      '
        else:
            lines += ['  const auto& operands = value.operands;\n']
        lines += [f'{indent}output += {json.dumps(" layout=" + layout.identity.name)};\n']
        for field in layout.fields:
            lines += [f'{indent}output += {json.dumps(" " + field.identity.name + "=")} + to_string(operands.{identifier(field.cpp_name)});\n']
        if len(form.layouts) > 1:
            lines += ['      break;\n    }\n']
    if len(form.layouts) > 1:
        lines += ['    default: return output + " <invalid-layout>";\n  }\n']
    lines += ['  return output;\n}\n']
    return ''.join(lines)


def dispatch_source(model: Snapshot) -> str:
    """Reference every exact freeze/check/print thunk from complete dense tables."""
    lines = [_warning(), '#include <array>\n#include <ptxsim/exec_ir/instruction_base.gen.hpp>\nnamespace ptxsim::exec_ir {\n']
    for form in model.forms:
        name = form.cpp_name
        lines += [f'/** @brief Exact owned shape validator for {name}. */\nauto validate_{name}(const Instruction&) noexcept -> bool;\n',
                  f'/** @brief Complete owned field formatter for {name}. */\nauto print_{name}(const Instruction&) -> std::string;\n',
                  f'/** @brief Actual const deep-copy factory for {name}. */\nauto freeze_{name}(const Instruction&) -> std::unique_ptr<const Instruction>;\n']
